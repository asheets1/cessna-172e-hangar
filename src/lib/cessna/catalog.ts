import { SPEC } from "./specs";
import type { Connection, Part, PartRole, SystemId } from "./types";

function p(
  id: string,
  name: string,
  system: SystemId,
  role: PartRole,
  material: string,
  notes: string,
  extra: Partial<Part> = {},
): Part {
  return {
    id,
    name,
    system,
    role,
    qty: extra.qty ?? 1,
    material,
    spec: extra.spec,
    finish: extra.finish,
    weightLb: extra.weightLb,
    notes,
    connections: extra.connections ?? [],
    source: extra.source ?? "SM-100 / POH-172E",
  };
}

function c(to: string, via: Connection["via"], spec: string, note?: string): Connection {
  return { to, via, spec, note };
}

const ribs = (side: "L" | "R"): Part[] =>
  Array.from({ length: SPEC.wing.ribCount }, (_, i) => {
    const n = String(i + 1).padStart(2, "0");
    const station = (i / (SPEC.wing.ribCount - 1)) * (SPEC.wing.semiSpan - 22);
    return p(
      `WING-${side}-RIB-${n}`,
      `${side === "L" ? "Left" : "Right"} wing rib ${i + 1}`,
      "wing",
      "structure",
      "2024-T3 Alclad, formed",
      `Nose-rib / intermediate rib at ${station.toFixed(0)} in from side of body. Lightening holes, spar slots at 25% and 68% chord, flange width ~0.5 in. Inboard ribs carry bladder-tank straps.`,
      {
        spec: `STA ${station.toFixed(0)}`,
        connections: [
          c(`WING-${side}-SPAR-MAIN`, "MS rivet", "AD-4 / AD-5", "Spar web and cap"),
          c(`WING-${side}-SPAR-REAR`, "MS rivet", "AD-4", "Rear spar web"),
          c(`WING-${side}-SKIN-UPPER`, "MS rivet", "AD-4 stagger", "Upper skin"),
          c(`WING-${side}-SKIN-LOWER`, "MS rivet", "AD-4 stagger", "Lower skin"),
        ],
      },
    );
  });

