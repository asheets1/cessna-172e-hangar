export const PARTS_BY_ID: Record<string, Part> = Object.fromEntries(PARTS.map((x) => [x.id, x]));

export function resolvePart(id: string): Part {
  const found = PARTS_BY_ID[id];
  if (found) return found;
  const prefix = id.split("-")[0];
  const systemMap: Record<string, SystemId> = {
    FUS: "fuselage",
    WING: "wing",
    EMP: "empennage",
    GEAR: "landing-gear",
    ENG: "powerplant",
    PROP: "propeller",
    CTL: "flight-controls",
    FUEL: "fuel",
    ELE: "electrical",
    INS: "instruments",
    INT: "interior",
    CWL: "cowling",
  };
  return p(
    id,
    id.replace(/-/g, " ").toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase()),
    systemMap[prefix ?? ""] ?? "fuselage",
    "structure",
    "2024-T3",
    "Sub-component of the 172E reconstruction.",
    { source: "SM-100" },
  );
}

export function partsForSystem(system: SystemId): Part[] {
  return PARTS.filter((p) => p.system === system);
}

